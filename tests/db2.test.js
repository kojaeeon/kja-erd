import test from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {blank, demo, sql, validate, termType} from '../src/model.js';

test('new designs default to DB2 and DB2 documents validate and generate native DDL',()=>{
  assert.equal(blank().dialect,'db2');const d=demo();assert.equal(validate(d).dialect,'db2');
  const t=d.tables[1];t.indexes.push({id:'ix',name:'ix_title',columns:[t.columns[2].id],unique:false});
  const result=sql(d);assert.deepEqual(result.errors,[]);
  assert.match(result.text,/INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY/);
  assert.match(result.text,/"post_content" CLOB/);assert.match(result.text,/"published_dt" TIMESTAMP/);
  assert.match(result.text,/CREATE INDEX "ix_title" ON "blog_post" \("post_title"\)/);
  assert.match(result.text,/ALTER TABLE "blog_post" ADD FOREIGN KEY/);
  assert.match(result.text,/COMMENT ON TABLE "blog_post" IS '게시글'/);
  assert.ok(result.text.lastIndexOf('CREATE TABLE')<result.text.indexOf('ALTER TABLE'));
  assert.doesNotMatch(result.text,/PRAGMA|AUTOINCREMENT|AUTO_INCREMENT|\bTEXT\b|\bDATETIME\b/);
});
test('single-table DB2 output contains only its DDL, indexes and outgoing foreign keys',()=>{
  const d=demo(),t=d.tables[1];t.indexes.push({id:'ix',name:'ix_post_title',columns:[t.columns[2].id],unique:true});
  const result=sql(d,t.id);assert.deepEqual(result.errors,[]);assert.deepEqual(result.externalTables,['blog_author']);
  assert.equal((result.text.match(/CREATE TABLE /g)||[]).length,1);
  assert.match(result.text,/CREATE TABLE "blog_post"/);assert.match(result.text,/REFERENCES "blog_author"/);
  assert.match(result.text,/CREATE UNIQUE INDEX "ix_post_title"/);
  assert.doesNotMatch(result.text,/CREATE TABLE "blog_author"|ALTER TABLE "blog_post_to_category"|COMMENT ON TABLE "blog_category"/);
});
