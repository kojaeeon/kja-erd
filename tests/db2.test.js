test('single-table SQLite output executes with existing referenced table and includes only its indexes',()=>{
  const d=demo('sqlite'),t=d.tables[1];t.indexes.push({id:'ix',name:'ix_title',columns:[t.columns[2].id],unique:false});
  const db=new DatabaseSync(':memory:');try{db.exec(sql(d,d.tables[0].id).text);db.exec(sql(d,t.id).text);
    assert.equal(db.prepare("SELECT COUNT(*) AS n FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'").get().n,2);
    db.prepare('INSERT INTO blog_author(display_name) VALUES (?)').run('author');
    db.prepare('INSERT INTO blog_post(author_id) VALUES (?)').run(1);
    assert.throws(()=>db.prepare('INSERT INTO blog_post(author_id) VALUES (?)').run(999));
  }finally{db.close();}
});
test('DB2 converts legacy types and escapes logical comments and identifiers',()=>{
  const d=demo('sqlite');d.dialect='db2';d.tables[1].logical="게시글 '설명'";
  const result=sql(d);assert.deepEqual(result.errors,[]);assert.match(result.text,/"display_name" CLOB/);
  assert.match(result.text,/"published_dt" TIMESTAMP/);assert.match(result.text,/IS '게시글 ''설명'''/);
  d.tables[0].name='author"name';assert.match(sql(d,d.tables[0].id).text,/CREATE TABLE "author""name"/);
});
test('DB2 rejects unsupported identity, decimal and LOB key definitions',()=>{
  const d=demo(),c=d.tables[0].columns[0];
  c.type='VARCHAR(100)';assert.ok(sql(d).errors.some(e=>e.includes('IDENTITY')));
  c.type='DECIMAL(32,0)';assert.ok(sql(d).errors.some(e=>e.includes('1~31')));
  c.type='DECIMAL(15,2)';assert.ok(sql(d).errors.some(e=>e.includes('IDENTITY')));
  c.type='BIGINT';c.default='0';assert.ok(sql(d).errors.some(e=>e.includes('DEFAULT')));
  c.default='';assert.deepEqual(sql(d).errors,[]);
  const another=d.tables[0].columns[1];another.ai=true;another.type='INTEGER';assert.ok(sql(d).errors.some(e=>e.includes('테이블당 하나')));
  another.ai=false;another.type='CLOB';another.unique=true;assert.ok(sql(d).errors.some(e=>e.includes('LOB/XML')));
});
